#!/usr/bin/env python3
"""Derive the experimental circuit v3+IMT from the v3 main circuit (issue #24): only the per-hop revocation check changes
(circomlib SMTVerifier exclusion -> indexed Merkle tree non-membership, IMTNonMember(RD)). Run from revocation_imt/."""
src = open("../zkdac_v3/circuits/zkdac_chain_v3.circom").read()
hdr = "// GENERATED by revocation_imt/scripts/make_v3_imt.py from zkdac_v3/circuits/zkdac_chain_v3.circom — do not edit. Issue #24.\n"
s = src.replace('include "circomlib/circuits/smt/smtverifier.circom";', 'include "imt.circom";')
s = s.replace("    signal input r_sib[D][RD]; signal input r_oldKey[D]; signal input r_oldValue[D]; signal input r_isOld0[D];",
              "    signal input r_low_value[D]; signal input r_low_next_index[D]; signal input r_low_next_value[D];\n"
              "    signal input r_sib[D][RD]; signal input r_bit[D][RD];      // IMT path of the low leaf (RD = IMT depth)")
old = """        rv[i] = SMTVerifier(RD);
        rv[i].enabled <== 1; rv[i].fnc <== 1;          // fnc=1: non-inclusion
        rv[i].root <== revoked_root;
        for (var j = 0; j < RD; j++) { rv[i].siblings[j] <== r_sib[i][j]; }
        rv[i].oldKey <== r_oldKey[i]; rv[i].oldValue <== r_oldValue[i]; rv[i].isOld0 <== r_isOld0[i];
        rv[i].key <== cert[i]; rv[i].value <== 0;"""
new = """        rv[i] = IMTNonMember(RD);                      // indexed Merkle tree non-membership (issue #24)
        rv[i].root <== revoked_root; rv[i].key_full <== cert[i];
        rv[i].low_value <== r_low_value[i]; rv[i].low_next_index <== r_low_next_index[i]; rv[i].low_next_value <== r_low_next_value[i];
        for (var j = 0; j < RD; j++) { rv[i].sib[j] <== r_sib[i][j]; rv[i].bit[j] <== r_bit[i][j]; }"""
assert old in s
s = s.replace(old, new).replace("template ZkDacChainV3(", "template ZkDacChainV3IMT(")
assert "SMTVerifier" not in s and "r_oldKey" not in s
open("circuits/zkdac_chain_v3_imt.circom", "w").write(hdr + s)
for d in (1, 2, 3, 4):
    open(f"circuits/main_v3imt_d{d}.circom", "w").write(f'pragma circom 2.1.6;\ninclude "zkdac_chain_v3_imt.circom";\ncomponent main {{public [issued_root, revoked_root, nullifier, now, ctx_hash, act_req_cap]}} = ZkDacChainV3IMT({d}, 16, 20);\n')
